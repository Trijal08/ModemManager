const MMSitBootRequest *
mm_sit_boot_requests (gsize *n_requests)
{
    *n_requests = G_N_ELEMENTS (boot_requests);
    return boot_requests;
}

/* How many times to send this on `stack`; see MMSitBootRequest.repeat. */
guint
mm_sit_boot_request_repeat (const MMSitBootRequest *request, guint stack)
{
    guint n = request->repeat[stack ? 1 : 0];

    return n ? n : 1;
}

gboolean
mm_sit_boot_request_wanted (const MMSitBootRequest *request, guint stack)
{
    return request->stacks == MM_SIT_BOOT_STACKS_ALL || stack == 0;
}

guint8 *
mm_sit_boot_build_payload (const MMSitBootRequest *request, gsize *len)
{
    if (request->sub != MM_SIT_BOOT_SUB_BUILD)
        return NULL;
    if (request->id == 0x0106)
        return build_broadcast_sms_config (len);
    g_warn_if_reached ();
    return NULL;
}
